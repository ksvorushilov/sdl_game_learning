static SDL_Texture *alphabet[ALPHABET_LENGTH];

static bool is_alphabet_generated = false;

void fill_texture(SDL_Renderer *renderer,
                  SDL_Texture *letter,
                  const unsigned char letter_map[FONT_HEIGHT][FONT_WIDTH]);

void generate_alphabet(SDL_Renderer *renderer)
{
    if (is_alphabet_generated)
        return;
    for (int i = 0; i < ALPHABET_LENGTH; i++)
    {
        alphabet[i] = SDL_CreateTexture(
            renderer, SDL_PIXELFORMAT_RGBA8888, SDL_TEXTUREACCESS_TARGET,
            FONT_HEIGHT + 1, FONT_WIDTH + 1);
        if (!alphabet[i]) // chat gpt recommended verification step
        {
            printf("Texture creation failed at index %d: %s\n",
                   i, SDL_GetError());
            return;
        }

        SDL_SetTextureBlendMode(alphabet[i], SDL_BLENDMODE_BLEND); // chat gpt recommended for better alpha behaviour. No idea
        fill_texture(renderer, alphabet[i], FONT[i]);
    }
    is_alphabet_generated = true;
}

void fill_texture(SDL_Renderer *renderer,
                  SDL_Texture *letter,
                  const unsigned char letter_map[FONT_HEIGHT][FONT_WIDTH])
{
    SDL_RendererInfo info;

    if (SDL_GetRendererInfo(renderer, &info) != 0)
        printf("Failed to get renderer info: %s", SDL_GetError());
    else
    {
        if (!(info.flags & SDL_RENDERER_TARGETTEXTURE))
            printf("Render targets are NOT supported.");
    }

    SDL_SetRenderTarget(renderer, letter);
    SDL_SetRenderDrawColor(renderer, 0, 0, 0, 0);
    SDL_RenderClear(renderer);

    SDL_SetRenderDrawColor(renderer, 255, 255, 255, 255);
    SDL_Rect rect = {0, 0, 1, 1};
    for (int i = 0; i < FONT_HEIGHT; i++)
    {
        for (int j = 0; j < FONT_WIDTH; j++)
        {
            rect.x = i;
            rect.y = j;
            if (letter_map[j][i])
                SDL_RenderFillRect(renderer, &rect);
        }
    }
    SDL_SetRenderTarget(renderer, NULL);
}

void print_sdl(SDL_Renderer *renderer,
               const char *str,
               const point_2d *pos,
               unsigned int size)
{
    if (!is_alphabet_generated)
        generate_alphabet(renderer);
    SDL_Rect rect = {pos->x, pos->y, size, size};
    for (; *str; str++)
    {
        char sym = *str;
        if (sym >= 'A' && sym <= 'Z')
            SDL_RenderCopy(renderer, alphabet[sym - 'A'], NULL, &rect);
        else if (sym >= 'a' && sym <= 'z')
            SDL_RenderCopy(renderer, alphabet[toupper(sym) - 'A'], NULL, &rect);
        else if (sym >= '0' && sym <= '9')
            SDL_RenderCopy(renderer, alphabet['Z' - 'A' + 1 + sym - '0'], NULL, &rect);
        rect.x += size;
    }
}

void destroy_alphabet(void)
{
    for (int i = 0; i < ALPHABET_LENGTH; i++)
    {
        SDL_DestroyTexture(alphabet[i]);
        alphabet[i] = NULL;
    }
}